#!/usr/bin/env python3
"""
Regression test: the generalised tool must reproduce the hand-written one.

The original `tools/splat/georef.py` had every constant inlined for one site.
This checks that driving the same site from a config file produces bit-for-bit
the same fit, scale, residuals, checks and crop geometry.

    python3 geo/test_georef.py [path/to/reference/geo.json]

Also unit-tests the parts with no site in them: the Mercator round-trip, and
the reflection guard that catches a mirrored render.
"""
import json
import math
import os
import subprocess
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import geocore  # noqa: E402

# The reference is a FIXTURE, captured from git before the live geo.json was
# regenerated by this tool. Pointing at the live file would be self-referential
# the moment we deploy to it, and the test would quietly stop proving anything.
# This is the output of the original hand-written tools/splat/georef.py.
DEFAULT_REF = os.path.join(HERE, "fixtures", "reference_mountain-view.geo.json")

FAILED = []


def check(label, got, want, tol=0.0):
    ok = (got == want) if tol == 0 else (abs(got - want) <= tol)
    print(f"  {'PASS' if ok else 'FAIL'}  {label:<34} {got!r}"
          + ("" if ok else f"   expected {want!r}"))
    if not ok:
        FAILED.append(label)


def test_mercator():
    print("\nMercator")
    m = geocore.Mercator(37.834408, -122.230258, 2400.0, 2048)
    check("m_per_px", m.m_per_px, 1.171875)
    i, j = m.to_px(-122.230258, 37.834408)
    check("centre -> px x", round(i, 9), 1024.0)
    check("centre -> px y", round(j, 9), 1024.0)
    lon, lat = m.to_lonlat(1024, 1024)
    check("px -> lon", round(lon, 9), -122.230258)
    check("px -> lat", round(lat, 9), 37.834408)
    # a non-centre point must round-trip too
    lon2, lat2 = m.to_lonlat(300.0, 1700.0)
    i2, j2 = m.to_px(lon2, lat2)
    check("off-centre round-trip x", round(i2, 6), 300.0)
    check("off-centre round-trip y", round(j2, 6), 1700.0)


def test_reflection_guard():
    """A mirrored render must NOT be absorbed as a clean rotation.

    This is the determinant -1 bug GEOREF.md records. If the fit were allowed
    to reflect, a flipped render would fit perfectly and the error would be
    invisible from inside the project.
    """
    print("\nReflection guard")
    src = [(0.0, 0.0), (100.0, 0.0), (0.0, 50.0), (80.0, 60.0)]
    th = math.radians(20.0)
    R = np.array([[math.cos(th), -math.sin(th)], [math.sin(th), math.cos(th)]])
    dst_clean = [tuple(2.0 * (R @ np.array(p)) + np.array([10.0, -5.0])) for p in src]
    f = geocore.fit_similarity(src, dst_clean)
    check("recovers scale", round(f.scale, 9), 2.0)
    check("recovers rotation", round(f.deg, 7), 20.0)

    # now mirror the destination in x. A reflection-allowing fit would score 0
    # residual; ours must not.
    dst_mirror = [(-x, y) for x, y in dst_clean]
    fm = geocore.fit_similarity(src, dst_mirror)
    r = max(np.hypot(*(fm.fwd(p) - np.asarray(q)))
            for p, q in zip(src, dst_mirror))
    print(f"  {'PASS' if r > 1.0 else 'FAIL'}  mirrored fit refuses to close  "
          f"max residual {r:.1f} px (must be large)")
    if r <= 1.0:
        FAILED.append("reflection guard")
    check("det(R) > 0 always", bool(np.linalg.det(fm.R) > 0.999), True)


def test_against_reference(ref_path):
    print(f"\nAgainst reference\n  {ref_path}")
    if not os.path.exists(ref_path):
        print("  SKIP  reference geo.json not found")
        return
    ref = json.load(open(ref_path))

    out = os.path.join(HERE, "out", "_test")
    subprocess.run([sys.executable, os.path.join(HERE, "georef.py"),
                    "--site", "mountain-view", "--out", out],
                   check=True, capture_output=True)
    got = json.load(open(os.path.join(out, "geo.json")))

    for k in ("scale", "deg", "tx", "ty", "residual_max_m"):
        check(f"fit.{k}", got["fit"][k], ref["fit"][k])
    for i, (g, r) in enumerate(zip(got["fit"]["residual_m"],
                                   ref["fit"]["residual_m"])):
        check(f"fit.residual_m[{i}]", g, r)
    for k in ("m_per_render_px", "m_per_unit", "north_bearing_deg"):
        check(f"scale.{k}", got["scale"][k], ref["scale"][k])
    for k in ("mean_speed_ms", "mean_speed_kmh"):
        check(f"check.{k}", got["check"][k], ref["check"][k])
    # launch_offset_m is allowed 1e-6 m of slack, and only this field.
    # The original hardcoded the held-out point as the tile centre, literally
    # (NAIP_PX/2, NAIP_PX/2). This version projects the holdout's lon/lat
    # through the inverse Mercator, so it works for a holdout anywhere on the
    # tile rather than only at its centre. Round-tripping through log/atan/exp
    # lands 2.8e-10 px off exact, which is 3.5e-10 m here. That is the entire
    # difference; it is a nanometre-scale artefact of being more general.
    check("check.launch_offset_m", got["check"]["launch_offset_m"],
          ref["check"]["launch_offset_m"], tol=1e-6)
    for k in ("w", "h", "m_per_px"):
        check(f"aerial.{k}", got["aerial"][k], ref["aerial"][k])
    for k in ("nw", "se"):
        check(f"aerial.{k}", got["aerial"][k], ref["aerial"][k])
    for k in sorted(ref["metric"]):
        check(f"metric.{k}", got["metric"].get(k), ref["metric"][k])
    # the control pins the figure draws
    for a, b in zip(got["fit"]["control"], ref["fit"]["control"]):
        check(f"aerial_px {a['name'][:20]}", a["aerial_px"], b["aerial_px"])


if __name__ == "__main__":
    ref = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_REF
    test_mercator()
    test_reflection_guard()
    test_against_reference(ref)
    print()
    if FAILED:
        print(f"{len(FAILED)} FAILED: {FAILED}")
        raise SystemExit(1)
    print("all passed")
